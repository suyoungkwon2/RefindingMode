export const getSessionById = (id: string): Session | undefined =>
  sessions.find((s) => s.id === id);

export const sidebarGroups = (): { label: string; sessions: Session[] }[] => {
  const today = new Date('2026-05-24');
  const result = [
    { label: '오늘', sessions: [] as Session[] },
    { label: '어제', sessions: [] as Session[] },
    { label: '최근 7일', sessions: [] as Session[] },
    { label: '최근 30일', sessions: [] as Session[] },
    { label: '이전', sessions: [] as Session[] },
  ];

  for (const s of [...sessions].sort((a, b) => b.date.localeCompare(a.date))) {
    const diff = Math.floor((today.getTime() - new Date(s.date).getTime()) / 86400000);
    if (diff === 0) result[0].sessions.push(s);
    else if (diff === 1) result[1].sessions.push(s);
    else if (diff <= 7) result[2].sessions.push(s);
    else if (diff <= 30) result[3].sessions.push(s);
    else result[4].sessions.push(s);
  }

  return result.filter((g) => g.sessions.length > 0);
};
